func waitPhase8BirdRoute(t *testing.T, ctx context.Context, socket, prefix string) {
	t.Helper()
	deadline := time.Now().Add(20 * time.Second)
	for time.Now().Before(deadline) {
		output, err := exec.CommandContext(ctx, "birdc", "-s", socket, "show", "route", prefix).CombinedOutput()
		if err == nil && strings.Contains(string(output), prefix) {
			return
		}
		time.Sleep(250 * time.Millisecond)
	}
	t.Fatalf("BIRD %s did not learn %s", socket, prefix)
}

func waitPhase8TCP(ctx context.Context, address string) error {
	deadline := time.Now().Add(15 * time.Second)
	for time.Now().Before(deadline) {
		conn, err := (&net.Dialer{Timeout: time.Second}).DialContext(ctx, "tcp", address)
		if err == nil {
			_ = conn.Close()
			return nil
		}
		time.Sleep(200 * time.Millisecond)
	}
	return fmt.Errorf("service %s did not become ready", address)
}

func assertPhase8Route(t *testing.T, ctx context.Context, netns, address, want string) {
	t.Helper()
	args := []string{"route", "get", address}
	if netns != "" {
		args = append([]string{"netns", "exec", netns, "ip"}, args...)
	}
	output, err := exec.CommandContext(ctx, "ip", args...).CombinedOutput()
	if err != nil || !strings.Contains(string(output), want) {
		t.Fatalf("ip %s: %v\n%s\nwant %q", strings.Join(args, " "), err, output, want)
	}
}
