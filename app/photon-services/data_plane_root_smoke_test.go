func startPhase8Bird(t *testing.T, ctx context.Context, netns, config, socket, pid string) {
	t.Helper()
	if output, err := exec.CommandContext(ctx, "ip", "netns", "exec", netns, "bird", "-c", config, "-s", socket, "-P", pid).CombinedOutput(); err != nil {
		t.Fatalf("start BIRD in %s: %v\n%s", netns, err, output)
	}
	deadline := time.Now().Add(10 * time.Second)
	for time.Now().Before(deadline) {
		if _, err := os.Stat(socket); err == nil {
			return
		}
		time.Sleep(100 * time.Millisecond)
	}
	t.Fatalf("BIRD control socket %s did not appear", socket)
}

